/**
 * The Freery end to end test.
 *
 *   node scripts/smoke-test.mjs
 *
 * It exercises the parts the briefs make promises about:
 *   - the GPS ingest route: the device key, the validation and the
 *     duplicate sequence number
 *   - the mode separation: the phone process never serves the admin routes,
 *     the head station process never serves the counting routes
 *   - the role rules: only the head administrator can change a ferry or a
 *     station, the station staff cannot
 *   - the counting rules: the count cannot go below zero or above the
 *     capacity, and a retried tap is counted once
 *   - the fleet management: a ferry or a station the master administrator adds
 *     shows up on the passenger site straight away, and can be taken off again
 *
 * The admin process has to be running on 3001 and the station phone process
 * on 3002. It prints one line per check and exits with 1 if anything fails.
 */

import { existsSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(here, "..");
const repoRoot = resolve(appRoot, "..", "..");

const ADMIN = "http://127.0.0.1:3001";
const PHONE = "http://127.0.0.1:3002";
/** The read-only API and the passenger website that reads from it. */
const LIVE_API = "http://127.0.0.1:4000";
const PASSENGER_SITE = "http://127.0.0.1:3000";

const ACCOUNTS = {
  admin: { username: "admin", password: "" },
  staff: { username: "staff", password: "" },
};

let passed = 0;
let failed = 0;

/* --- helpers ------------------------------------------------------------- */

function readEnvFileAt(path) {
  const values = {};
  try {
    for (const rawLine of readFileSync(path, "utf8").split(/\r?\n/)) {
      const line = rawLine.trim();
      if (!line || line.startsWith("#")) continue;
      const split = line.indexOf("=");
      if (split === -1) continue;
      values[line.slice(0, split).trim()] = line.slice(split + 1).trim();
    }
  } catch {
    // The file is optional. The environment can carry the same values.
  }
  return values;
}

function readEnvFile(name) {
  return readEnvFileAt(join(appRoot, name));
}

const adminEnv = readEnvFile(".env.local");
const DEVICE_KEY = process.env.DEVICE_API_KEY ?? adminEnv.DEVICE_API_KEY ?? "";

/**
 * The read-only API only answers requests that carry the shared secret, so
 * the test needs it to look at the live fleet. The secret lives in the
 * read-only API's own env file; the browser never sees it.
 */
const liveApiEnv = readEnvFileAt(join(repoRoot, "apps", "readonly-api", ".env.local"));
const API_SECRET = process.env.API_SECRET ?? liveApiEnv.API_SECRET ?? "";

/**
 * The head administrator account.
 *
 * The password is generated by the database setup and kept in .secrets,
 * because it is never written into the application. The test looks for it in
 * the same places a person would.
 */
function findAdminAccount() {
  const jsonPath = join(repoRoot, ".secrets", "admin-login.json");
  if (existsSync(jsonPath)) {
    try {
      const parsed = JSON.parse(readFileSync(jsonPath, "utf8"));
      if (parsed?.password) {
        return {
          username: parsed.username ?? parsed.email ?? "admin",
          password: parsed.password,
        };
      }
    } catch {
      // Fall through to the readable file.
    }
  }

  const txtPath = join(repoRoot, ".secrets", "admin-login.txt");
  if (existsSync(txtPath)) {
    const text = readFileSync(txtPath, "utf8");
    const password = text.match(/^Password:\s*(\S+)\s*$/m)?.[1];
    const username = text.match(/^Username:\s*(\S+)\s*$/m)?.[1];
    if (password) return { username: username ?? "admin", password };
  }

  if (process.env.ADMIN_PASSWORD) {
    return { username: "admin", password: process.env.ADMIN_PASSWORD };
  }
  if (adminEnv.ADMIN_PASSWORD) {
    return { username: "admin", password: adminEnv.ADMIN_PASSWORD };
  }

  return { username: "admin", password: "" };
}

const adminAccount = findAdminAccount();
ACCOUNTS.admin.username = adminAccount.username;
ACCOUNTS.admin.password = adminAccount.password;

if (!ACCOUNTS.admin.password) {
  console.error(
    "\nThe head administrator password was not found.\n" +
      "Looked at ADMIN_PASSWORD, apps/admin/.env.local and .secrets/admin-login.json.\n" +
      "Run 'node scripts/setup.mjs' in packages/database to create the accounts.\n",
  );
  process.exit(1);
}

/**
 * The station account the test signs in with.
 *
 * The password is not written into this file, so no credential sits in the
 * repository. It is read from the same place the head administrator password
 * is read from: the last password in .secrets/admin-login.txt, which belongs
 * to the station accounts, or the environment.
 */
function findStaffPassword() {
  if (process.env.STAFF_PASSWORD) return process.env.STAFF_PASSWORD;

  const txtPath = join(repoRoot, ".secrets", "admin-login.txt");
  if (existsSync(txtPath)) {
    const text = readFileSync(txtPath, "utf8");
    const matches = [...text.matchAll(/^Password:\s*(\S+)\s*$/gm)];
    const station = matches[matches.length - 1];
    if (station) return station[1];
  }

  return "";
}

ACCOUNTS.staff.password = findStaffPassword();

if (!ACCOUNTS.staff.password) {
  console.error(
    "\nThe station account password was not found.\n" +
      "Looked at STAFF_PASSWORD and .secrets/admin-login.txt.\n",
  );
  process.exit(1);
}

function check(label, actual, expected) {
  const good = String(actual) === String(expected);
  if (good) {
    passed += 1;
    console.log(`  PASS  ${label} (${actual})`);
  } else {
    failed += 1;
    console.log(`  FAIL  ${label} (got ${actual}, expected ${expected})`);
  }
}

function truthy(label, value) {
  if (value) {
    passed += 1;
    console.log(`  PASS  ${label}`);
  } else {
    failed += 1;
    console.log(`  FAIL  ${label}`);
  }
}

/** A tiny cookie jar, enough for one signed in session. */
function makeJar() {
  const cookies = new Map();
  return {
    header() {
      return [...cookies.entries()]
        .map(([name, value]) => `${name}=${value}`)
        .join("; ");
    },
    absorb(response) {
      const lines = response.headers.getSetCookie?.() ?? [];
      for (const line of lines) {
        const [pair] = line.split(";");
        const split = pair.indexOf("=");
        if (split === -1) continue;
        cookies.set(pair.slice(0, split).trim(), pair.slice(split + 1).trim());
      }
    },
  };
}

async function call(url, { jar, ...options } = {}) {
  const headers = new Headers(options.headers ?? {});
  const cookie = jar?.header();
  if (cookie) headers.set("cookie", cookie);
  const response = await fetch(url, { ...options, headers, redirect: "manual" });
  jar?.absorb(response);
  return response;
}

/**
 * Follows a redirect by hand.
 *
 * The suite never lets fetch follow a redirect on its own, because a redirect
 * that leads to the login page must be seen as a failure, not as a page.
 */
async function follow(url, jar) {
  const response = await call(url, { jar });
  const status = response.status;
  if (status < 300 || status >= 400) return response;
  const location = response.headers.get("location");
  if (!location) return response;
  const next = location.startsWith("http") ? location : `${ADMIN}${location}`;
  return call(next, { jar });
}

/** Calls the read-only API with the secret it asks for. */
async function callLive(path, options = {}) {
  const headers = new Headers(options.headers ?? {});
  if (API_SECRET) headers.set("x-api-secret", API_SECRET);
  return call(`${LIVE_API}${path}`, { ...options, headers });
}

/**
 * Waits for a record to turn up on a list endpoint.
 *
 * The passenger website keeps its answer for a few seconds, so a ferry that
 * was just added is not on the site yet. The test waits for it rather than
 * failing on a cache that has not expired.
 */
async function waitForId(fetchList, key, id, timeoutMs = 15000) {
  const deadline = Date.now() + timeoutMs;
  let ids = [];
  while (Date.now() < deadline) {
    const response = await fetchList();
    ids = (await body(response))?.[key]?.map((item) => item.id) ?? [];
    if (ids.includes(id)) return ids;
    await new Promise((resolve) => setTimeout(resolve, 500));
  }
  return ids;
}

/**
 * Waits for a record to come off a list endpoint.
 *
 * The mirror of waitForId, used when a ferry or a station is taken away
 * again.
 */
async function waitForGone(fetchList, key, id, timeoutMs = 15000) {
  const deadline = Date.now() + timeoutMs;
  let ids = [];
  while (Date.now() < deadline) {
    const response = await fetchList();
    ids = (await body(response))?.[key]?.map((item) => item.id) ?? [];
    if (!ids.includes(id)) return ids;
    await new Promise((resolve) => setTimeout(resolve, 500));
  }
  return ids;
}

async function body(response) {
  const text = await response.text();
  try {
    return JSON.parse(text);
  } catch {
    return text;
  }
}

/** Signs in with the credentials provider and returns the cookie jar. */
async function signIn(base, account) {
  const jar = makeJar();
  const csrf = await call(`${base}/api/auth/csrf`, { jar });
  const { csrfToken } = await body(csrf);

  const form = new URLSearchParams({
    csrfToken,
    username: account.username,
    password: account.password,
    callbackUrl: `${base}/`,
  });

  const response = await call(`${base}/api/auth/callback/credentials`, {
    jar,
    method: "POST",
    headers: { "content-type": "application/x-www-form-urlencoded" },
    body: form.toString(),
  });

  return {
    jar,
    status: response.status,
    location: response.headers.get("location") ?? "",
  };
}

/**
 * A successful sign in redirects to the page the person asked for. A failed
 * one redirects to the error page, which carries 'error=' in the address.
 * Checking only for 302 would let a wrong password look like a good login.
 */
function checkSignIn(label, result) {
  const rejected = result.location.includes("error=");
  if (result.status === 302 && !rejected) {
    passed += 1;
    console.log(`  PASS  ${label} (302)`);
    return;
  }
  failed += 1;
  console.log(
    `  FAIL  ${label} (status ${result.status}, redirect "${result.location || "none"}")`,
  );
}

